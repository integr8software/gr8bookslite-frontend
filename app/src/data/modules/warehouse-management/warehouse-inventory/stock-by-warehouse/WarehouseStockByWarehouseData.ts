export function createWarehouseStockByWarehouseRecords(
  module: WarehouseStockByWarehouseModule,
): WarehouseStockByWarehouseRecord[] {
  return moduleRows[module].map((cells, index) => {
    const warehouse =
      MockWarehousesData[index % MockWarehousesData.length] ?? MockWarehousesData[0];
    return {
      cells,
      id: `${module}-${index + 1}`,
      status: cells.status ?? "Active",
      warehouseId: warehouse.id,
      warehouseName: warehouse.name,
    };
  });
}
