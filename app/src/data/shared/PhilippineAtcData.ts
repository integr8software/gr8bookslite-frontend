export function normalizePhilippineAtcCode(value: string) {
	const compactCode = value.trim().toUpperCase().replace(/\s+/g, "");

	if (/^MC\d{3}$/.test(compactCode)) {
		return compactCode;
	}

	return compactCode.replace(/^([A-Z]{2})(\d{3})$/, "$1 $2");
}

export function isPhilippineAtcCodeLike(value: string) {
	const compactCode = value.trim().toUpperCase().replace(/\s+/g, "");

	return /^(W[BCIV]\d{3}|MC\d{3})$/.test(compactCode);
}

export function getPhilippineAtcPartyClassification(code: string) {
	const normalizedCode = normalizePhilippineAtcCode(code);

	if (normalizedCode.startsWith("WI ")) {
		return "individual";
	}

	if (normalizedCode.startsWith("WC ")) {
		return "nonIndividual";
	}

	return "shared";
}

function getOfficialAtcCode(
	taxCode: string,
	taxAlias: string | null,
	atc: string | null,
) {
	const officialCode = [atc, taxAlias, taxCode].find(
		(value): value is string => Boolean(value && isPhilippineAtcCodeLike(value)),
	);

	return officialCode ? normalizePhilippineAtcCode(officialCode) : null;
}
