function section(
  key: string,
  title: string,
  href: string,
  icon: MainNavigationSection["icon"],
  accessKey: MainAccessKey,
  items: MainNavigationItem[],
): MainNavigationSection {
  return { key, title, href, icon, accessKey, items };
}

function group(
  key: string,
  label: string,
  href: string,
  accessKey: MainAccessKey,
  children: MainNavigationItem[],
): MainNavigationItem {
  return { key, label, href, accessKey, productKey: "core", children };
}

function moduleItem(
  key: string,
  label: string,
  moduleCode: ModuleCode,
  accessKey: MainAccessKey,
  productKey: MainProductKey = "core",
  productKeys?: MainProductKey[],
  actions: MainModuleAction[] = CrudActions,
): MainNavigationItem {
  return {
    key,
    label,
    href: MODULE_ROUTE_MAP[moduleCode],
    accessKey,
    permissionCode: moduleCode,
    productKey,
    productKeys,
    requiredActions: ["view"],
    module: {
      actions,
      recordIds: ModuleRecordIds,
    },
  };
}
